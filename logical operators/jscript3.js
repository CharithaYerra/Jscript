let rollNo=53;
let name="siri";


//logical and ----> &&

console.log("the results of logical and are:")

console.log(rollNo=='53' && name=="siri");
console.log(rollNo=='53' && name=="Siri");
console.log(rollNo==54 && name=="siri");
console.log(rollNo==54 && name=="Siri");


//logical or ---->  ||

console.log("the results of logical OR are:")


console.log(rollNo=='53' || name=="siri");
console.log(rollNo=='53' || name=="Siri");
console.log(rollNo==54 || name=="siri");
console.log(rollNo==54 || name=="Siri");