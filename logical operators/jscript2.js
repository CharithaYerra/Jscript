//logical operators

//logical and -  &&

if(5 && "string"){
    console.log("In logical operator if the two conditions is true then result is true")
}

if(0 && 1){
    console.log("the output of false and true in logical && is false");
}

if(false && 0){
    
    console.log("if both statement are false the output will be false");

}


//logical or-- ||

if(5 || "string"){
    console.log("In logical operator if the two conditions is true then result is true")
}

if(0 || 1){
    console.log("the output of false and true in logical || is true");
}

if(false || 0){
    
    console.log("if both statement are false the output will be false");

}

